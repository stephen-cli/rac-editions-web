/**
 * Refuses game data in the repository.
 *
 * The editions are built from each player's own discs, so nothing here may hold a game's data: no disc
 * images, executables, archives, audio or video taken from a disc. .gitignore keeps the usual files out,
 * but a forced add or a renamed file gets past it, so this check reads the files themselves.
 *
 *   node scripts/check-game-data.ts                  every tracked file
 *   node scripts/check-game-data.ts --staged         the files staged for the next commit (the pre-commit hook)
 *   node scripts/check-game-data.ts --range A..B     also every file each commit in A..B adds or changes
 *
 * --range covers files a later commit deletes again, since history keeps them. Exits 1 on any finding.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, statSync } from 'node:fs';
import { extname, posix } from 'node:path';

interface Candidate {
  path: string;
  label: string;
  read: () => Buffer;
}

// Disc images, PS2 executables and IOP modules, memory card saves, and the games' archives, sound and video.
const GAME_EXTENSIONS = new Set([
  '.iso', '.bin', '.img', '.cue', '.mdf', '.nrg', '.elf', '.irx',
  '.ps2', '.psu', '.max', '.mcd',
  '.wad', '.bnk', '.vag', '.vb', '.hd', '.bd', '.sck', '.pss', '.ipu',
]);
// A PS2 disc's boot executable (SCES_509.16) and system files.
const DISC_NAMES = /^(SCES|SCUS|SLES|SLUS|SCPS|SLPS|SCKA|SCAJ)_\d{3}\.\d{2}$|^(SYSTEM\.CNF|IOPRP\d*\.IMG)$/i;
// Binary files are allowed only as the site's own images and fonts.
const BINARY_OK = new Set(['.png', '.webp', '.avif', '.jpg', '.ico', '.woff2']);
const MAX_BYTES = 256 * 1024;
const MAX_IMAGE_BYTES = 1024 * 1024;
// Files over the limit on purpose, with why.
const LARGE_OK = new Map([['pnpm-lock.yaml', 'the lockfile, generated by pnpm']]);

function git(...args: string[]): Buffer {
  return execFileSync('git', args, { maxBuffer: 1 << 30 });
}

function problem(path: string, data: Buffer): string | null {
  const name = posix.basename(path);
  const ext = extname(name).toLowerCase();
  if (DISC_NAMES.test(name)) return "a PlayStation 2 disc file's name";
  if (GAME_EXTENSIONS.has(ext)) return `a game data extension (${ext})`;
  if (data.subarray(0, 4).equals(Buffer.from('\x7fELF', 'latin1'))) return 'an ELF executable';
  if ([0x8001, 0x8801, 0x9001].some((at) => data.subarray(at, at + 5).toString('latin1') === 'CD001')) {
    return 'an ISO 9660 disc image';
  }
  const limit = BINARY_OK.has(ext) ? MAX_IMAGE_BYTES : MAX_BYTES;
  if (data.length > limit && !LARGE_OK.has(path)) return `${data.length} bytes, over the ${limit} byte limit`;
  if (!BINARY_OK.has(ext) && data.subarray(0, 8000).includes(0)) return 'binary content';
  return null;
}

function tracked(): Candidate[] {
  return git('ls-files', '-z')
    .toString()
    .split('\0')
    .filter((path) => path && statSync(path, { throwIfNoEntry: false })?.isFile())
    .map((path) => ({ path, label: path, read: () => readFileSync(path) }));
}

function staged(): Candidate[] {
  return git('diff', '--cached', '--name-only', '--diff-filter=AMRC', '-z')
    .toString()
    .split('\0')
    .filter(Boolean)
    .map((path) => ({ path, label: `${path} (staged)`, read: () => git('show', `:${path}`) }));
}

function changedIn(range: string): Candidate[] {
  const found: Candidate[] = [];
  for (const commit of git('rev-list', ...range.split(/\s+/)).toString().split(/\s+/).filter(Boolean)) {
    // -z rows: ":mode mode sha sha status", then the path, or two paths for a rename or copy.
    const rows = git('diff-tree', '-r', '--no-commit-id', '--root', '--diff-filter=AMRC', '-z', commit)
      .toString()
      .split('\0');
    for (let i = 0; i + 1 < rows.length; ) {
      const [, , , sha, status] = rows[i]!.split(' ');
      i += status!.startsWith('R') || status!.startsWith('C') ? 2 : 1;
      const path = rows[i++]!;
      found.push({ path, label: `${path} in ${commit.slice(0, 12)}`, read: () => git('cat-file', 'blob', sha!) });
    }
  }
  return found;
}

const args = process.argv.slice(2);
const rangeAt = args.indexOf('--range');
const files = args.includes('--staged')
  ? staged()
  : [...tracked(), ...(rangeAt >= 0 ? changedIn(args[rangeAt + 1] ?? '') : [])];

let refused = 0;
for (const file of files) {
  const why = problem(file.path, file.read());
  if (why) {
    console.log(`game data? ${file.label}: ${why}`);
    refused++;
  }
}
console.log(`${files.length} files checked, ${refused} refused${refused ? '' : ': no game data'}`);
process.exitCode = refused ? 1 : 0;
